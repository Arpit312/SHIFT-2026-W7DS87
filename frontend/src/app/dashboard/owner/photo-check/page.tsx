'use client';
import { Suspense } from 'react';

import { useSearchParams } from 'next/navigation';
import { useQuery } from '@tanstack/react-query';
import { api } from '@/lib/api-client';
import { Card, CardContent, CardHeader, CardTitle, CardDescription } from '@/components/ui/card';
import { Skeleton } from '@/components/ui/skeleton';
import { ErrorState } from '@/components/ui/error-state';
import { EmptyState } from '@/components/ui/empty-state';
import { SeverityBadge } from '@/components/ui/severity-badge';
import { Button } from '@/components/ui/button';
import { formatDateTime, formatConfidence } from '@/lib/utils';
import { Download, ShieldAlert, CheckCircle2, Info, AlertTriangle } from 'lucide-react';
import { VERDICT_LABELS, type Verdict } from '@/lib/constants';
import { DemoDataBanner } from '@/components/ui/demo-data-banner';

function PhotoCheckPageInner() {
  const searchParams = useSearchParams();
  const requestId = searchParams?.get('id');

  const { data: requests, isLoading: isRequestsLoading } = useQuery({
    queryKey: ['owner-requests'],
    queryFn: () => api.getRequests(),
    enabled: !requestId,
  });

  const activeId = requestId || (requests?.results?.[0]?.id);

  const { data: assessments, isLoading, error, refetch } = useQuery({
    queryKey: ['assessments', activeId],
    queryFn: () => api.getAssessments(activeId!),
    enabled: !!activeId,
  });

  const latestAssessment = assessments?.results?.[0];

  const getVerdictIcon = (verdict: Verdict) => {
    switch (verdict) {
      case 'pass': return <CheckCircle2 className="w-6 h-6 text-success" />;
      case 'pass_with_conditions': return <AlertTriangle className="w-6 h-6 text-warning" />;
      case 'fail': return <ShieldAlert className="w-6 h-6 text-danger" />;
      case 'manual_review_required': return <Info className="w-6 h-6 text-info" />;
      default: return null;
    }
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold font-heading text-text-primary">Safety Report</h1>
          <p className="text-text-muted mt-1">AI-assisted preliminary photo screening results.</p>
        </div>
      </div>

      <DemoDataBanner message="This report is generated by a mock AI service for Phase 1 testing." />

      {error ? (
        <ErrorState message="Failed to load safety report" onRetry={() => refetch()} />
      ) : isRequestsLoading || (isLoading && activeId) ? (
        <Skeleton className="h-[300px] w-full" />
      ) : !activeId ? (
        <EmptyState title="No active request" description="You need an active charging request to view a Photo Check report." />
      ) : !latestAssessment ? (
        <EmptyState title="Report pending" description="Your photos are being analyzed. Please check back shortly." />
      ) : (
        <>
          <div className="grid md:grid-cols-3 gap-6">
            <Card className="md:col-span-2">
              <CardHeader>
                <CardTitle>Overall Assessment</CardTitle>
              </CardHeader>
              <CardContent className="space-y-6">
                <div className="flex items-center gap-4 p-4 bg-surface rounded-lg border border-cn-border">
                  {getVerdictIcon(latestAssessment.overall_verdict as Verdict)}
                  <div>
                    <h3 className="font-bold text-lg">{VERDICT_LABELS[latestAssessment.overall_verdict as Verdict] || latestAssessment.overall_verdict}</h3>
                    {latestAssessment.overall_confidence && (
                      <p className="text-sm text-text-muted mt-1">
                        Confidence: {formatConfidence(latestAssessment.overall_confidence)}
                      </p>
                    )}
                  </div>
                </div>

                {latestAssessment.findings && latestAssessment.findings.length > 0 && (
                  <div>
                    <h4 className="font-semibold mb-3">Key Findings</h4>
                    <div className="space-y-3">
                      {latestAssessment.findings.map((finding: any, idx: number) => (
                        <div key={idx} className="flex items-start justify-between p-3 bg-surface rounded-lg">
                          <p className="text-sm text-text-primary pr-4">{finding.observation}</p>
                          <SeverityBadge severity={finding.severity} />
                        </div>
                      ))}
                    </div>
                  </div>
                )}
              </CardContent>
            </Card>

            <div className="space-y-6">
              <Card>
                <CardHeader>
                  <CardTitle className="text-sm font-semibold text-text-muted">Report Details</CardTitle>
                </CardHeader>
                <CardContent className="space-y-3">
                  <div>
                    <p className="text-xs text-text-muted">Date Assessed</p>
                    <p className="text-sm font-medium">{formatDateTime(latestAssessment.assessed_at)}</p>
                  </div>
                  <div>
                    <p className="text-xs text-text-muted">Version</p>
                    <p className="text-sm font-medium">v{latestAssessment.assessment_version}</p>
                  </div>
                  {latestAssessment.requires_human_review && (
                    <div className="mt-4 p-3 bg-warning/10 text-warning rounded-lg text-sm flex items-start gap-2">
                      <AlertTriangle className="w-4 h-4 shrink-0 mt-0.5" />
                      <p>This report has been flagged for mandatory human review by an electrician.</p>
                    </div>
                  )}
                </CardContent>
              </Card>

              {latestAssessment.limitations && latestAssessment.limitations.length > 0 && (
                <Card className="bg-surface/50 border-dashed">
                  <CardContent className="p-4">
                    <h4 className="text-xs font-semibold text-text-muted uppercase tracking-wider mb-2">Technical Limitations</h4>
                    <ul className="text-xs text-text-muted space-y-1 list-disc pl-3">
                      {latestAssessment.limitations.map((lim: string, i: number) => (
                        <li key={i}>{lim}</li>
                      ))}
                    </ul>
                  </CardContent>
                </Card>
              )}
            </div>
          </div>

          {latestAssessment.suggested_conditions && latestAssessment.suggested_conditions.length > 0 && (
            <Card>
              <CardHeader>
                <CardTitle>Suggested Corrective Actions</CardTitle>
                <CardDescription>The RWA may require you to complete these actions.</CardDescription>
              </CardHeader>
              <CardContent>
                <div className="space-y-4">
                  {latestAssessment.suggested_conditions.map((cond: any, idx: number) => (
                    <div key={idx} className="p-4 border border-cn-border rounded-lg bg-surface">
                      <h4 className="font-semibold text-sm">{cond.title}</h4>
                      <p className="text-sm text-text-muted mt-1">{cond.explanation}</p>
                      <div className="mt-3 text-sm">
                        <span className="font-medium text-brand-orange">Required Action:</span> {cond.required_action}
                      </div>
                    </div>
                  ))}
                </div>
              </CardContent>
            </Card>
          )}
        </>
      )}
    </div>
  );
}

export default function PhotoCheckPage() {
  return (
    <Suspense fallback={<Skeleton className="h-[500px] w-full" />}>
      <PhotoCheckPageInner />
    </Suspense>
  );
}
